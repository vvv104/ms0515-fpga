#!/usr/bin/env python3
"""The parts list of НС4 for a board made anew (docs/plan.md stage 8).

    python tools/bom.py          - write docs/pcb/bom.md
    python tools/bom.py check    - the same without writing (exit 1 when it
                                   is stale or a part has no footprint)

Every part of netlist/parts.csv (ПЭ3) with its footprint and what can stand
in for it: a chip takes a DIP by its pin count (15.24 mm wide from 24
pins, as tools/footprints.py lays them) and its analogue from
docs/chips.md; any other part its type's line of netlist/packages.csv.  A
chip that sits in a socket of ПЭ3 (the ROMs, the processor, the drive
controller) is not placed itself: the socket is.
"""
import csv
import os
import re
import sys
from collections import defaultdict
from dataclasses import dataclass

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIDE = 24

# The chips in the sockets XS3..XS6 (variants: «XS3..XS6 the DIP sockets
# under D65, D77 (28 pins) and D1, D83 (40 pins)»): which socket under which
# chip is not on the drawing, so they pair in the order of their numbers.
SOCKETS = {"D65": "XS3", "D77": "XS4", "D1": "XS5", "D83": "XS6"}


@dataclass
class Item:
    ref: str
    type: str
    value: str
    footprint: str
    equivalent: str
    note: str = ""
    placed: bool = True


@dataclass
class Line:
    type: str
    value: str
    refs: list
    equivalent: str
    footprint: str
    note: str


def rows(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(line for line in f if not line.startswith("#")))


def dip(pins):
    width = "15.24" if pins >= WIDE else "7.62"
    return f"Package_DIP:DIP-{pins}_W{width}mm"


def analogues(chips_md):
    """{chip type: analogue} from the table of docs/chips.md."""
    found = {}
    with open(chips_md, encoding="utf-8") as f:
        for line in f:
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 3 and re.match(r"^К", cells[0]):
                found[cells[0]] = cells[2]
    return found


def is_chip(ref):
    return re.fullmatch(r"D\d+", ref) is not None


def items(parts_path, packages_path, chips_md, firmware_path):
    """{ref: Item} and the problems: parts without a footprint or analogue."""
    packages = {r["type"]: r for r in rows(packages_path)}
    firmware = {r["ref"]: r for r in rows(firmware_path)}
    analogue = analogues(chips_md)
    found, problems = {}, []
    for r in rows(parts_path):
        ref, kind, value = r["ref"], r["type"], r["value"] or ""
        if is_chip(ref):
            if kind not in analogue:
                problems.append(f"{ref}: no analogue of {kind} in docs/chips.md")
            item = Item(ref, kind, value, dip(int(r["pins"])), analogue.get(kind, ""))
            notes = []
            if ref in firmware:
                notes.append(f"programmed: {firmware[ref]['file']}, {firmware[ref]['format']}")
            if ref in SOCKETS:
                item.placed = False
                notes.append(f"in the socket {SOCKETS[ref]}")
            item.note = "; ".join(notes)
        elif kind in packages:
            p = packages[kind]
            item = Item(ref, kind, value, p["footprint"], p["equivalent"] or "", p["note"] or "")
        else:
            problems.append(f"{ref}: no footprint for {kind} in netlist/packages.csv")
            continue
        found[ref] = item
    return found, problems


def natural(text):
    return [int(s) if s.isdigit() else s for s in re.split(r"(\d+)", text)]


def lines(found):
    """The parts list: one line a type and value, its references in order."""
    groups = defaultdict(list)
    for item in found.values():
        groups[(item.type, item.value, item.footprint if item.placed else "", item.note)].append(item)
    out = []
    for (kind, value, _, _), group in groups.items():
        first = group[0]
        out.append(Line(kind, value, sorted((i.ref for i in group), key=natural), first.equivalent,
                        first.footprint if first.placed else "", first.note))
    return sorted(out, key=lambda l: natural(l.refs[0]))


def markdown(table):
    text = ["| Type | Value | Qty | References | Equivalent | Footprint | Note |",
            "|---|---|---|---|---|---|---|"]
    for l in table:
        footprint = f"`{l.footprint}`" if l.footprint else ""
        text.append(f"| {l.type} | {l.value} | {len(l.refs)} | {', '.join(l.refs)} | {l.equivalent} | {footprint} "
                    f"| {l.note} |")
    return "\n".join(text) + "\n"


HEAD = """# НС4: the parts list for a board made anew

Generated by `tools/bom.py` from `netlist/parts.csv` (3.858.420 ПЭ3),
`netlist/packages.csv` and the analogues of `docs/chips.md` - do not edit.
The board is built as 3.858.420 (`netlist/variants.md`): the МС 7004 on
XS2, SA1's odd switches closed; ROM-B in the sockets XS3, XS4.

"""


def main(argv):
    check = argv[1:] == ["check"]
    found, problems = items(os.path.join(ROOT, "netlist", "parts.csv"),
                            os.path.join(ROOT, "netlist", "packages.csv"),
                            os.path.join(ROOT, "docs", "chips.md"),
                            os.path.join(ROOT, "netlist", "firmware.csv"))
    for p in problems:
        print("error:", p)
    text = HEAD + markdown(lines(found))
    target = os.path.join(ROOT, "docs", "pcb", "bom.md")
    old = open(target, encoding="utf-8").read() if os.path.exists(target) else None
    if check:
        if old != text:
            print("stale: docs/pcb/bom.md")
        return 1 if problems or old != text else 0
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
