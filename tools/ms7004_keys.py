#!/usr/bin/env python3
"""The PC keyboard's tables for the МС 7004 translator of the MiSTer core.

    python tools/ms7004_keys.py          - write rtl/parts/ms7004_keys_pkg.sv
    python tools/ms7004_keys.py check    - the same without writing (exit 1
                                           when the committed file is stale)

From netlist/ms7004/pc_keys.csv (a PC key: its PS/2 code, the МС 7004 key
it is in each mode) and netlist/ms7004/matrix.csv (an МС 7004 key's place:
its scan line ВР and return line ГР).  A place in the matrix is
(ГР - 1) * 16 + (ВР - 1).
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.join(HERE, "..")
NETLIST = os.path.join(REPO, "netlist", "ms7004")
OUT = os.path.join(REPO, "rtl", "parts", "ms7004_keys_pkg.sv")

# what a character needs of the МС 7004's ВР: as the PC's Shift, let go, pressed
SHIFT = {"=": 0, "0": 1, "+": 2}


def rows(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(line for line in f if not line.startswith("#")))


def places():
    """SAn -> its place in the matrix."""
    out = {}
    for r in rows(os.path.join(NETLIST, "matrix.csv")):
        vr, gr = int(r["vr"][2:]), int(r["gr"][2:])
        out[r["sa"]] = (gr - 1) * 16 + (vr - 1)
    return out


def ps2(text):
    """'e07C' -> 0x17C (bit 8: extended), '1C' -> 0x01C."""
    ext = text.lower().startswith("e0")
    return (0x100 if ext else 0) | int(text[2:] if ext else text, 16)


def entry(cell, where, problems, name):
    """'SA46+' -> (place, shift); '' -> None."""
    cell = cell.strip()
    if not cell:
        return None
    m = re.fullmatch(r"(SA\d+)\s*([=0+])", cell)
    if not m or m.group(1) not in where:
        problems.append(f"{name}: '{cell}' is no key of the matrix")
        return None
    return where[m.group(1)], SHIFT[m.group(2)]


def tables():
    """The positional and character tables and the problems found."""
    where = places()
    problems, pos, char, seen = [], {}, {}, set()
    for r in rows(os.path.join(NETLIST, "pc_keys.csv")):
        code = ps2(r["ps2"])
        if code in seen:
            problems.append(f"{r['pc']}: PS/2 {r['ps2']} twice")
        seen.add(code)
        if r["pos"] not in where:
            problems.append(f"{r['pc']}: '{r['pos']}' is no key of the matrix")
            continue
        pos[code] = where[r["pos"]]
        for col, shifted, rus in (("lat", 0, 0), ("lat_s", 1, 0), ("rus", 0, 1), ("rus_s", 1, 1)):
            e = entry(r[col], where, problems, r["pc"])
            if e:
                lat = 1 if rus and not shifted and r["rus_lat"] == "1" else 0
                char[code, shifted, rus] = (e[0], e[1], lat)
    return pos, char, where, problems


def text(pos, char, where):
    lines = [
        "// The PC keyboard's tables for the МС 7004 translator (rtl/parts/ms7004_keys.sv),",
        "// generated by tools/ms7004_keys.py from netlist/ms7004/pc_keys.csv and",
        "// matrix.csv - do not edit.  A key's place in the matrix: (ГР - 1) * 16 +",
        "// (ВР - 1); the top bit of each entry tells there is one.",
        "package ms7004_keys_pkg;",
        f"    localparam logic [6:0] SHIFT_L = 7'd{where['SA8']};     // ВР",
        f"    localparam logic [6:0] RUS_LAT = 7'd{where['SA15']};     // РУС/ЛАТ",
        "",
        "    // the positional mode: {valid, place}",
        "    function automatic logic [7:0] position(logic [8:0] code);",
        "        case (code)",
    ]
    lines += [f"            9'h{c:03X}: return 8'h{0x80 | p:02X};" for c, p in sorted(pos.items())]
    lines += ["            default: return 8'h00;", "        endcase", "    endfunction", "",
              "    // the character mode: {valid, place, ВР (0 as the PC's Shift, 1 let go,",
              "    // 2 pressed), ЛАТ needed}, by the code, the PC's Shift, РУС mode",
              "    function automatic logic [10:0] character(logic [8:0] code, logic shift, logic rus);",
              "        case ({code, shift, rus})"]
    for (c, s, r), (p, sh, lat) in sorted(char.items()):
        value = (1 << 10) | (p << 3) | (sh << 1) | lat
        lines.append(f"            {{9'h{c:03X}, 1'b{s}, 1'b{r}}}: return 11'h{value:03X};")
    lines += ["            default: return 11'h000;", "        endcase", "    endfunction",
              "endpackage", ""]
    return "\n".join(lines)


def main(argv):
    pos, char, where, problems = tables()
    for p in problems:
        print("error: " + p)
    out = text(pos, char, where)
    if len(argv) > 1 and argv[1] == "check":
        with open(OUT, encoding="utf-8") as f:
            stale = f.read() != out
        if stale:
            print("error: rtl/parts/ms7004_keys_pkg.sv is stale")
        return 1 if stale or problems else 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
